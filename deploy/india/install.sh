#!/usr/bin/env bash
# One-command installer for OpenOMS (India build) on a fresh Ubuntu/Debian server.
#
#   curl -fsSL https://raw.githubusercontent.com/caanshulgarg/openoms-india/main/deploy/india/install.sh | sudo bash
#
# What it does:
#   1. Installs Docker if it is missing, and adds swap on small servers.
#   2. Downloads this repository to /opt/openoms-india.
#   3. Writes .env with freshly generated secrets (kept on later runs).
#   4. Builds and starts PostgreSQL, Redis, the API, the dashboard and an
#      HTTPS reverse proxy (Caddy, automatic Let's Encrypt certificate).
#   5. Creates the first company and owner login and prints them.
#
# It is safe to run again: secrets, data and the owner login are kept, and the
# app is rebuilt from the latest code.
#
# Optional settings (environment variables):
#   OPENOMS_DOMAIN       Host name pointing at this server. Default: a free
#                        <ip>.sslip.io name derived from the public IP.
#   OPENOMS_ADMIN_EMAIL  Owner login email.      Default: admin@openoms.local
#   OPENOMS_COMPANY      Company (tenant) name.  Default: My Company
#   OPENOMS_DIR          Install directory.      Default: /opt/openoms-india
#   OPENOMS_REPO         Git URL to install from.
#   OPENOMS_SKIP_FETCH   1 = use the code already in OPENOMS_DIR (used by CI).
set -euo pipefail

OPENOMS_DIR="${OPENOMS_DIR:-/opt/openoms-india}"
OPENOMS_REPO="${OPENOMS_REPO:-https://github.com/caanshulgarg/openoms-india.git}"
OPENOMS_ADMIN_EMAIL="${OPENOMS_ADMIN_EMAIL:-admin@openoms.local}"
OPENOMS_COMPANY="${OPENOMS_COMPANY:-My Company}"
OPENOMS_TENANT_SLUG="main"
LOGIN_FILE="${OPENOMS_LOGIN_FILE:-/root/openoms-login.txt}"

say() { printf '\n==> %s\n' "$*"; }
die() { printf '\nERROR: %s\n' "$*" >&2; exit 1; }

[ "$(id -u)" -eq 0 ] || die "Run this as root (put 'sudo' before 'bash')."

# ── 1. Prerequisites ──────────────────────────────────────────────────────
if ! command -v docker >/dev/null 2>&1; then
  say "Installing Docker"
  command -v curl >/dev/null 2>&1 || { apt-get update -y && apt-get install -y curl; }
  curl -fsSL https://get.docker.com | sh
fi
docker compose version >/dev/null 2>&1 || die "Docker Compose v2 is required (docker compose). Install the docker-compose-plugin package."
command -v git >/dev/null 2>&1 || { say "Installing git"; apt-get update -y && apt-get install -y git; }
command -v openssl >/dev/null 2>&1 || { say "Installing openssl"; apt-get update -y && apt-get install -y openssl; }

# Building the dashboard needs roughly 3 GB of memory. Add swap on small servers.
mem_kb="$(awk '/MemTotal/ {print $2}' /proc/meminfo)"
swap_kb="$(awk '/SwapTotal/ {print $2}' /proc/meminfo)"
if [ "${OPENOMS_SKIP_SWAP:-0}" != "1" ] && [ "$mem_kb" -lt 3900000 ] && [ "$swap_kb" -lt 1000000 ] && [ ! -e /swapfile ]; then
  say "Adding a 3 GB swap file (server has less than 4 GB RAM)"
  fallocate -l 3G /swapfile || dd if=/dev/zero of=/swapfile bs=1M count=3072
  chmod 600 /swapfile
  mkswap /swapfile >/dev/null
  swapon /swapfile
  grep -q '^/swapfile ' /etc/fstab || echo '/swapfile none swap sw 0 0' >> /etc/fstab
fi

# ── 2. Code ───────────────────────────────────────────────────────────────
if [ "${OPENOMS_SKIP_FETCH:-0}" = "1" ]; then
  [ -f "$OPENOMS_DIR/docker-compose.prod.yml" ] || die "OPENOMS_SKIP_FETCH=1 but $OPENOMS_DIR has no docker-compose.prod.yml"
elif [ -d "$OPENOMS_DIR/.git" ]; then
  say "Updating code in $OPENOMS_DIR"
  git -C "$OPENOMS_DIR" pull --ff-only
else
  say "Downloading code to $OPENOMS_DIR"
  git clone --depth 1 "$OPENOMS_REPO" "$OPENOMS_DIR"
fi
cd "$OPENOMS_DIR"

# ── 3. Configuration ──────────────────────────────────────────────────────
if [ ! -f .env ]; then
  if [ -z "${OPENOMS_DOMAIN:-}" ]; then
    public_ip="$(curl -fsS --max-time 10 https://api.ipify.org || curl -fsS --max-time 10 https://ifconfig.me || true)"
    case "$public_ip" in
      *[!0-9.]*|"") die "Could not detect this server's public IPv4 address. Re-run with OPENOMS_DOMAIN=your.host.name" ;;
    esac
    OPENOMS_DOMAIN="$(printf '%s' "$public_ip" | tr '.' '-').sslip.io"
  fi
  say "Writing .env for https://$OPENOMS_DOMAIN"
  umask 077
  cat > .env <<EOF
# Generated by deploy/india/install.sh. Keep this file private and backed up:
# ENCRYPTION_KEY protects the stored carrier credentials and cannot be recovered.
OPENOMS_DOMAIN=$OPENOMS_DOMAIN
FRONTEND_URL=https://$OPENOMS_DOMAIN
BASE_URL=https://$OPENOMS_DOMAIN

POSTGRES_PASSWORD=$(openssl rand -hex 24)
POSTGRES_APP_PASSWORD=$(openssl rand -hex 24)
JWT_SECRET=$(openssl rand -hex 32)
ENCRYPTION_KEY=$(openssl rand -hex 32)

# Plain-HTTP ports stay on this machine only; the public entry is Caddy (443).
API_PORT=127.0.0.1:8080
DASHBOARD_PORT=127.0.0.1:3000

# Dashboard and API share one origin, so no absolute API URL is baked in.
NEXT_PUBLIC_API_URL=
DASHBOARD_API_PROXY_URL=http://api-server:8080

# India: show beta carriers (Shiprocket, Delhivery), rupees and India by default.
OPENOMS_API_SURFACE=full
OPENOMS_DASHBOARD_SURFACE=full
OPENOMS_DEFAULT_CURRENCY=INR
NEXT_PUBLIC_DEFAULT_CURRENCY=INR
NEXT_PUBLIC_DEFAULT_COUNTRY=IN

REGISTRATION_MODE=invite
WORKERS_ENABLED=true
FEATURE_ALLEGRO=false
FEATURE_INPOST=false
EOF
  umask 022
else
  say "Keeping existing .env"
fi
OPENOMS_DOMAIN="$(grep -E '^OPENOMS_DOMAIN=' .env | head -n1 | cut -d= -f2-)"
[ -n "$OPENOMS_DOMAIN" ] || die ".env has no OPENOMS_DOMAIN"

compose() { docker compose -f docker-compose.prod.yml -f deploy/india/docker-compose.hosted.yml "$@"; }

# ── 4. Build and start ────────────────────────────────────────────────────
say "Building and starting OpenOMS (first build takes 10-20 minutes)"
compose up -d --build

say "Waiting for the API to become healthy"
healthy=0
for _ in $(seq 1 90); do
  if curl -fsS --max-time 5 http://127.0.0.1:8080/health >/dev/null 2>&1; then healthy=1; break; fi
  sleep 4
done
if [ "$healthy" -ne 1 ]; then
  compose ps || true
  compose logs --tail 60 api-server migrate || true
  die "The API did not become healthy. The log lines above show why."
fi

# ── 5. First company and owner login ──────────────────────────────────────
psql_admin() { compose exec -T postgres psql -v ON_ERROR_STOP=1 -U openoms -d openoms "$@"; }

user_count="$(psql_admin -At -c 'SELECT count(*) FROM users' | tr -d '[:space:]')"
if [ "$user_count" = "0" ]; then
  say "Creating the first company and owner login"
  admin_password="$(openssl rand -base64 18 | tr -dc 'A-Za-z0-9' | cut -c1-16)"
  [ "${#admin_password}" -ge 12 ] || die "Could not generate a password"
  # bcrypt (cost 12) via Apache htpasswd; "$2y$" and "$2a$" are the same algorithm.
  password_hash="$(docker run --rm httpd:2.4-alpine htpasswd -nbBC 12 owner "$admin_password" | head -n1 | cut -d: -f2 | sed 's/^\$2y\$/$2a$/')"
  case "$password_hash" in
    '$2a$12$'*) ;;
    *) die "Could not hash the owner password" ;;
  esac

  psql_admin -q \
    -v company="$OPENOMS_COMPANY" -v slug="$OPENOMS_TENANT_SLUG" \
    -v email="$OPENOMS_ADMIN_EMAIL" -v hash="$password_hash" <<'SQL'
BEGIN;
INSERT INTO tenants (name, slug, plan, settings)
VALUES (:'company', :'slug', 'pro', '{"default_currency": "INR", "auto_confirm_orders": true}')
ON CONFLICT (slug) DO NOTHING;

INSERT INTO users (tenant_id, email, name, password_hash, role, language)
SELECT t.id, :'email', 'Owner', :'hash', 'owner', 'en'
FROM tenants t
WHERE t.slug = :'slug'
ON CONFLICT (tenant_id, email) DO NOTHING;
COMMIT;
SQL

  umask 077
  cat > "$LOGIN_FILE" <<EOF
OpenOMS login (created $(date -u +%Y-%m-%dT%H:%M:%SZ))
URL:          https://$OPENOMS_DOMAIN
Company slug: $OPENOMS_TENANT_SLUG
Email:        $OPENOMS_ADMIN_EMAIL
Password:     $admin_password
EOF
  umask 022
  created_login=1
else
  created_login=0
fi

say "OpenOMS is running"
echo "  Open:  https://$OPENOMS_DOMAIN"
if [ "$created_login" -eq 1 ]; then
  echo "  Company slug: $OPENOMS_TENANT_SLUG"
  echo "  Email:        $OPENOMS_ADMIN_EMAIL"
  echo "  Password:     $admin_password"
  echo
  echo "  These details are also saved in $LOGIN_FILE (readable by root only)."
  echo "  Change the password after your first login."
else
  echo "  An owner login already exists; it was left unchanged."
  [ -f "$LOGIN_FILE" ] && echo "  The original details are in $LOGIN_FILE."
fi
echo
echo "  The HTTPS certificate is issued on first visit; allow up to a minute."
echo "  Ports 80 and 443 must be open in your server provider's firewall."
